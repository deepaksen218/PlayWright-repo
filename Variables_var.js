// Variable used for storing values
// 3 types of variables in JavaScript: var, let, const

var a = 5; // Here var is used to declare a variable 'a' and assign it the value 5.
console.log(a); // This line prints the value of 'a' to the console, which is 5.
console.log("a"); // This line prints the string "a" to the console.

// if I need to change value of a from 5 to 20
a = 20; // Here we are reassigning the value of variable 'a' to 20.
console.log(a); // This line prints the updated value of 'a' to the console, which is 20.

// Checking the declaration of variable 'a' is possible 
var a = 40; // Here we are redeclaring the variable 'a' and assigning it a new value of 40.
console.log(a); // This line prints the new value of 'a' to the console, which is 40.

//Checking after declaring  is value is able to assign
var b;
b = 60;
console.log(b);

var name = "sen"; // Here we are declaring a variable 'name' and assigning it the string value "sen".
console.log(name); // This line prints the value of 'name' to the console, which is "sen".

var name = 'sen'; // single quotes can be used to declare
console.log(name);

var decimal = 10.5; // Here we are declaring a variable 'decimal' and assigning it the decimal value 10.5.
